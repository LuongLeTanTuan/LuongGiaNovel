CREATE POLICY "Backend stories write access" ON public.stories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Backend chapters write access" ON public.chapters;
CREATE POLICY "Backend chapters write access" ON public.chapters FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Backend categories write access" ON public.categories;
CREATE POLICY "Backend categories write access" ON public.categories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Backend story_categories write access" ON public.story_categories;
CREATE POLICY "Backend story_categories write access" ON public.story_categories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Backend users write access" ON public.users;
CREATE POLICY "Backend users write access" ON public.users FOR ALL USING (true) WITH CHECK (true);

