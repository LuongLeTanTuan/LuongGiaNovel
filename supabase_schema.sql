DROP POLICY IF EXISTS "Public chapters read access" ON public.chapters;
CREATE POLICY "Public chapters read access" ON public.chapters FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public categories read access" ON public.categories;
CREATE POLICY "Public categories read access" ON public.categories FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public story_categories read access" ON public.story_categories;
CREATE POLICY "Public story_categories read access" ON public.story_categories FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public users read access" ON public.users;
CREATE POLICY "Public users read access" ON public.users FOR SELECT USING (true);

