-- 7. KHỞI TẠO STORAGE BUCKETS (NẾU DÙNG SUPABASE STORAGE)
-- ==============================================
INSERT INTO storage.buckets (id, name, public)
VALUES 
  ('covers', 'covers', true),
  ('audios', 'audios', true)
ON CONFLICT (id) DO NOTHING;

-- Cho phép upload và xem file trong storage buckets công khai
DROP POLICY IF EXISTS "Public storage read covers" ON storage.objects;
CREATE POLICY "Public storage read covers" ON storage.objects FOR SELECT USING (bucket_id = 'covers');
DROP POLICY IF EXISTS "Public storage upload covers" ON storage.objects;
CREATE POLICY "Public storage upload covers" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'covers');
DROP POLICY IF EXISTS "Public storage update covers" ON storage.objects;
CREATE POLICY "Public storage update covers" ON storage.objects FOR UPDATE USING (bucket_id = 'covers');

DROP POLICY IF EXISTS "Public storage read audios" ON storage.objects;
CREATE POLICY "Public storage read audios" ON storage.objects FOR SELECT USING (bucket_id = 'audios');
DROP POLICY IF EXISTS "Public storage upload audios" ON storage.objects;
CREATE POLICY "Public storage upload audios" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'audios');
DROP POLICY IF EXISTS "Public storage update audios" ON storage.objects;
CREATE POLICY "Public storage update audios" ON storage.objects FOR UPDATE USING (bucket_id = 'audios');

