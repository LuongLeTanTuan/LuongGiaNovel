-- ==============================================
-- LƯƠNG GIA NOVEL - SUPABASE / POSTGRESQL SCHEMA
-- Cơ sở dữ liệu Cloud hiệu năng cao, lưu trữ trực tiếp
-- ==============================================

-- 1. BẢNG USERS & PHÂN QUYỀN (ROLES)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  full_name VARCHAR(100) DEFAULT 'Thành viên Lương Gia',
  role VARCHAR(20) DEFAULT 'user', -- 'admin', 'editor', 'user'
  avatar_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. BẢNG THỂ LOẠI (CATEGORIES)
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) UNIQUE NOT NULL,
  slug VARCHAR(100) UNIQUE NOT NULL,
  description TEXT
);

-- 3. BẢNG TRUYỆN (STORIES)
CREATE TABLE IF NOT EXISTS public.stories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE NOT NULL,
  author VARCHAR(100) DEFAULT 'Lương Gia Tác Giả',
  translator VARCHAR(100) DEFAULT 'Lương Gia Novel Team',
  cover_image TEXT,
  description TEXT,
  status VARCHAR(20) DEFAULT 'ongoing', -- 'ongoing', 'completed'
  audio_url TEXT,
  views BIGINT DEFAULT 0,
  likes BIGINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Bổ sung cột audio_url nếu bảng stories đã tồn tại từ trước
ALTER TABLE public.stories ADD COLUMN IF NOT EXISTS audio_url TEXT;

-- 4. BẢNG LIÊN KẾT TRUYỆN - THỂ LOẠI
CREATE TABLE IF NOT EXISTS public.story_categories (
  story_id BIGINT REFERENCES public.stories(id) ON DELETE CASCADE,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE CASCADE,
  PRIMARY KEY (story_id, category_id)
);

-- 5. BẢNG CHƯƠNG TRUYỆN (CHAPTERS)
CREATE TABLE IF NOT EXISTS public.chapters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id BIGINT REFERENCES public.stories(id) ON DELETE CASCADE,
  chapter_number INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  audio_url TEXT,
  word_count INT DEFAULT 0,
  views BIGINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(story_id, chapter_number)
);

-- Bổ sung cột audio_url nếu bảng chapters đã tồn tại từ trước
ALTER TABLE public.chapters ADD COLUMN IF NOT EXISTS audio_url TEXT;

-- ==============================================
-- 5.1. TỐI ƯU CHỈ MỤC INDEXES ĐỂ TĂNG TỐC ĐỘ TRUY VẤN
-- ==============================================
CREATE INDEX IF NOT EXISTS idx_stories_slug ON public.stories(slug);
CREATE INDEX IF NOT EXISTS idx_stories_status ON public.stories(status);
CREATE INDEX IF NOT EXISTS idx_stories_updated_at ON public.stories(updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_chapters_story_id ON public.chapters(story_id);
CREATE INDEX IF NOT EXISTS idx_chapters_story_slug ON public.chapters(story_id, slug);
CREATE INDEX IF NOT EXISTS idx_chapters_story_ch_num ON public.chapters(story_id, chapter_number);
CREATE INDEX IF NOT EXISTS idx_story_categories_story_id ON public.story_categories(story_id);
CREATE INDEX IF NOT EXISTS idx_story_categories_category_id ON public.story_categories(category_id);


-- ==============================================
-- 6. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================
ALTER TABLE public.stories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chapters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.story_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

